'use strict';
/* A tiny async SQL adapter. Local development uses SQLite; deployment uses
   Supabase PostgreSQL through pg (server-side only). No SQL enters the browser. */
const {AsyncLocalStorage}=require('node:async_hooks');
const scope=new AsyncLocalStorage();
const URL_KEY='SUPABASE_DB_URL';
function rewriteSql(sql){
  let statement=String(sql);
  statement=statement.replace(/INSERT\s+OR\s+IGNORE\s+INTO/gi,'INSERT INTO');
  statement=statement.replace(/\bMAX\s*\(\s*([^(),]+?)\s*,\s*0\s*\)/gi,'GREATEST($1,0)');
  statement=statement.replace(/\bMIN\s*\(\s*([^(),]+?)\s*,\s*0\s*\)/gi,'LEAST($1,0)');
  if(/\bINSERT\s+INTO\b/i.test(statement) && /\bOR\s+IGNORE\b/i.test(sql) && !/\bON\s+CONFLICT\b/i.test(statement)) statement+=' ON CONFLICT DO NOTHING';
  if(/^\s*INSERT\s+INTO\b/i.test(statement) && !/\bRETURNING\b/i.test(statement) && /\bINTO\s+(?:admins|services|boxes|payment_methods|portfolio|orders|customers|product_categories|products|product_requests|quotes|quote_items|quote_form_fields|quote_requests|business_accounts|studio_revisions)\b/i.test(statement))statement+=' RETURNING id';
  let i=0;return statement.replace(/\?/g,()=>`$${++i}`);
}
function convertDDL(sql){
  return sql.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bREAL\b/gi,'DOUBLE PRECISION')
    .replace(/TEXT\s+NOT\s+NULL\s+DEFAULT\s+CURRENT_TIMESTAMP/gi,'TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)')
    .replace(/ALTER\s+TABLE\s+(\w+)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/gi,'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ');
}
function openDb(filename){
  const connectionString=process.env[URL_KEY];
  if(process.env.VERCEL && !connectionString)throw new Error(`${URL_KEY} is required for Vercel to store customer orders permanently`);
  if(!connectionString){
    const {DatabaseSync}=require('node:sqlite');
    const client=new DatabaseSync(filename);
    client.exec('PRAGMA foreign_keys=ON; PRAGMA journal_mode=WAL;');
    function current(){return scope.getStore()?.sqlite || client;}
    return {prepare(sql){return {async get(...args){return current().prepare(sql).get(...args)},async all(...args){return current().prepare(sql).all(...args)},async run(...args){return current().prepare(sql).run(...args)}}},async exec(sql){return current().exec(sql)},async withTransaction(fn){client.exec('BEGIN IMMEDIATE');try{const result=await scope.run({sqlite:client},fn);client.exec('COMMIT');return result}catch(e){client.exec('ROLLBACK');throw e}},close(){client.close()}};
  }
  // Use the exact Transaction Pooler URL supplied by the Supabase dashboard.
  // Unnamed pg queries are compatible with Supabase's transaction pooler.
  const {Pool,types}=require('pg');
  // BIGINT identity IDs are safe integers in this application. Keep browser IDs numeric.
  types.setTypeParser(20,v=>Number(v));
  const pool=new Pool({connectionString,max:1,idleTimeoutMillis:10000,connectionTimeoutMillis:12000,allowExitOnIdle:true});
  async function execute(sql,params=[]){const q=scope.getStore()?.pg || pool;return q.query({text:rewriteSql(sql),values:params});}
  return {
    prepare(sql){return {
      async get(...args){const r=await execute(sql,args);return r.rows[0]},
      async all(...args){const r=await execute(sql,args);return r.rows},
      async run(...args){const r=await execute(sql,args);return {changes:r.rowCount,lastInsertRowid:r.rows[0]?.id ||0}}
    }},
    async exec(sql){
      const statements=convertDDL(sql).split(';').map(s=>s.trim()).filter(Boolean);
      for(const statement of statements)await execute(statement);
    },
    async withTransaction(fn){
      if(scope.getStore()?.pg) return fn();
      const client=await pool.connect();
      try{
        await client.query('BEGIN');
        // Serialize concurrent cold-start migrations/seeds across Vercel instances.
        await client.query('SELECT pg_advisory_xact_lock(774227)');
        const result=await scope.run({pg:client},fn);
        await client.query('COMMIT');return result;
      }catch(e){await client.query('ROLLBACK');throw e}finally{client.release()}
    },
    close(){return pool.end()}
  };
}
module.exports={openDb,rewriteSql,convertDDL};
