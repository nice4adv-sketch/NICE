-- Optional Supabase initialization. Run in SQL Editor as project owner.
-- The app also creates these tables automatically at initial connection.
BEGIN;

    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS admins (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS services (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      description TEXT DEFAULT '',
      icon TEXT DEFAULT '✦',
      active INTEGER NOT NULL DEFAULT 1,
      sort_order INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS boxes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      category TEXT NOT NULL,
      description TEXT DEFAULT '',
      specs TEXT DEFAULT '',
      image_url TEXT DEFAULT '',
      unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
      total_quantity INTEGER NOT NULL,
      reserved_quantity INTEGER NOT NULL DEFAULT 0,
      min_quantity INTEGER NOT NULL DEFAULT 1,
      deadline TEXT DEFAULT '',
      status TEXT NOT NULL DEFAULT 'active',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS payment_methods (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      type TEXT NOT NULL DEFAULT 'wallet',
      holder_name TEXT DEFAULT '',
      account_number TEXT DEFAULT '',
      instructions TEXT DEFAULT '',
      active INTEGER NOT NULL DEFAULT 1,
      sort_order INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS portfolio (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      category TEXT DEFAULT '',
      image_url TEXT NOT NULL,
      description TEXT DEFAULT '',
      active INTEGER NOT NULL DEFAULT 1,
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS orders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      box_id INTEGER NOT NULL,
      customer_name TEXT NOT NULL,
      shop_name TEXT DEFAULT '',
      phone TEXT NOT NULL,
      quantity INTEGER NOT NULL,
      unit_price DOUBLE PRECISION NOT NULL,
      total_amount DOUBLE PRECISION NOT NULL,
      payment_method_id INTEGER,
      payment_proof_url TEXT DEFAULT '',
      customer_logo_url TEXT DEFAULT '',
      note TEXT DEFAULT '',
      status TEXT NOT NULL DEFAULT 'pending',
      admin_note TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      FOREIGN KEY(box_id) REFERENCES boxes(id),
      FOREIGN KEY(payment_method_id) REFERENCES payment_methods(id)
    );
    CREATE TABLE IF NOT EXISTS customers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      business_name TEXT DEFAULT '',
      phone TEXT UNIQUE NOT NULL,
      email TEXT DEFAULT '',
      logo_url TEXT DEFAULT '',
      customer_type TEXT NOT NULL DEFAULT 'retail',
      notes TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS product_categories (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      slug TEXT UNIQUE NOT NULL,
      sort_order INTEGER NOT NULL DEFAULT 0,
      active INTEGER NOT NULL DEFAULT 1
    );
    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      slug TEXT UNIQUE NOT NULL,
      category_id INTEGER,
      sale_mode TEXT NOT NULL DEFAULT 'quote',
      pricing_mode TEXT NOT NULL DEFAULT 'quote',
      base_price DOUBLE PRECISION NOT NULL DEFAULT 0,
      unit_label TEXT DEFAULT 'قطعة',
      min_quantity INTEGER NOT NULL DEFAULT 1,
      description TEXT DEFAULT '',
      specs TEXT DEFAULT '',
      image_url TEXT DEFAULT '',
      options_json TEXT DEFAULT '[]',
      pricing_json TEXT DEFAULT '{}',
      requires_design INTEGER NOT NULL DEFAULT 0,
      production_source TEXT NOT NULL DEFAULT 'inhouse',
      active INTEGER NOT NULL DEFAULT 1,
      featured INTEGER NOT NULL DEFAULT 0,
      sort_order INTEGER NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      FOREIGN KEY(category_id) REFERENCES product_categories(id)
    );
    CREATE TABLE IF NOT EXISTS product_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      product_id INTEGER NOT NULL,
      customer_id INTEGER,
      customer_name TEXT NOT NULL,
      business_name TEXT DEFAULT '',
      phone TEXT NOT NULL,
      quantity INTEGER NOT NULL DEFAULT 1,
      configuration_json TEXT DEFAULT '{}',
      customer_file_url TEXT DEFAULT '',
      note TEXT DEFAULT '',
      unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
      total_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
      pricing_status TEXT NOT NULL DEFAULT 'awaiting_quote',
      payment_method_id INTEGER,
      payment_proof_url TEXT DEFAULT '',
      status TEXT NOT NULL DEFAULT 'new',
      admin_note TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      FOREIGN KEY(product_id) REFERENCES products(id),
      FOREIGN KEY(customer_id) REFERENCES customers(id),
      FOREIGN KEY(payment_method_id) REFERENCES payment_methods(id)
    );
    CREATE TABLE IF NOT EXISTS quotes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      request_id INTEGER,
      customer_id INTEGER,
      customer_name TEXT NOT NULL,
      business_name TEXT DEFAULT '',
      phone TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'draft',
      valid_until TEXT DEFAULT '',
      subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
      discount DOUBLE PRECISION NOT NULL DEFAULT 0,
      total DOUBLE PRECISION NOT NULL DEFAULT 0,
      notes TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      FOREIGN KEY(request_id) REFERENCES product_requests(id),
      FOREIGN KEY(customer_id) REFERENCES customers(id)
    );
    CREATE TABLE IF NOT EXISTS quote_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      quote_id INTEGER NOT NULL,
      description TEXT NOT NULL,
      quantity DOUBLE PRECISION NOT NULL DEFAULT 1,
      unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
      total DOUBLE PRECISION NOT NULL DEFAULT 0,
      sort_order INTEGER NOT NULL DEFAULT 0,
      FOREIGN KEY(quote_id) REFERENCES quotes(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS quote_form_fields (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      field_key TEXT UNIQUE NOT NULL,
      label TEXT NOT NULL,
      type TEXT NOT NULL DEFAULT 'text',
      required INTEGER NOT NULL DEFAULT 0,
      active INTEGER NOT NULL DEFAULT 1,
      sort_order INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS quote_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT UNIQUE NOT NULL,
      contact_name TEXT DEFAULT '',
      company_name TEXT NOT NULL,
      phone1 TEXT NOT NULL,
      phone2 TEXT DEFAULT '',
      phone3 TEXT DEFAULT '',
      location TEXT DEFAULT '',
      activity TEXT DEFAULT '',
      contract_type TEXT DEFAULT 'annual',
      fields_json TEXT DEFAULT '{}',
      items_json TEXT DEFAULT '[]',
      estimated_subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
      discount_min DOUBLE PRECISION NOT NULL DEFAULT 5,
      discount_max DOUBLE PRECISION NOT NULL DEFAULT 20,
      status TEXT NOT NULL DEFAULT 'new',
      admin_note TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS business_accounts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id INTEGER,
      company_name TEXT NOT NULL,
      contact_name TEXT DEFAULT '',
      phone TEXT NOT NULL,
      contract_type TEXT DEFAULT 'annual',
      status TEXT NOT NULL DEFAULT 'lead',
      start_date TEXT DEFAULT '',
      end_date TEXT DEFAULT '',
      credit_limit DOUBLE PRECISION NOT NULL DEFAULT 0,
      balance DOUBLE PRECISION NOT NULL DEFAULT 0,
      notes TEXT DEFAULT '',
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      FOREIGN KEY(customer_id) REFERENCES customers(id)
    );
  
CREATE TABLE IF NOT EXISTS studio_state (id INTEGER PRIMARY KEY CHECK(id=1),draft TEXT NOT NULL,published TEXT NOT NULL,draft_time TEXT NOT NULL,published_time TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS studio_template(id INTEGER PRIMARY KEY CHECK(id=1),snapshot TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS studio_revisions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,snapshot TEXT NOT NULL,note TEXT NOT NULL,created_at TEXT NOT NULL);
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.boxes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_methods ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.portfolio ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quote_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quote_form_fields ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quote_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.business_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studio_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studio_template ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studio_revisions ENABLE ROW LEVEL SECURITY;
COMMIT;
