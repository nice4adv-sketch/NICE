'use strict';
const assert=require('node:assert/strict');
const Module=require('node:module');
const origin=Module._load;
const calls=[];
const query=async function(req){const sql=typeof req==='string'?req:req.text;calls.push({sql,values:req.values||[]});if(/RETURNING id/i.test(sql))return {rows:[{id:17}],rowCount:1};if(/SELECT/i.test(sql))return {rows:[{id:17,other:'test'}],rowCount:1};return {rows:[],rowCount:1};};
class Pool{query(req){return query(req)}async connect(){return {query,release(){}}}end(){}}
const supabaseCalls=[];
let roleClient;
Module._load=function(name,...rest){
  if(name==='pg')return {Pool,types:{setTypeParser() {}}};
  if(name==='@supabase/supabase-js')return {
    createClient:(url,secret)=>{
      roleClient={url,secret};
      return {storage:{async getBucket(name){return {data:{name,public:name==='nice-public'},error:null}},from(bucket){
        return {
          async upload(file,bytes,opt){supabaseCalls.push({bucket,file,bytes,opt});return {data:{path:file},error:null}},
          getPublicUrl(file){return {data:{publicUrl:`${url}/storage/v1/object/public/${bucket}/${file}`}}},
          async download(file){supabaseCalls.push({bucket,file});return {data:new Blob(['private bytes'],{type:'image/png'}),error:null}}
        };
      }}};
    }
  };
  return origin.call(this,name,...rest);
};
async function main(){
  process.env.SUPABASE_DB_URL='postgresql://not-real.example';process.env.SUPABASE_URL='https://project.example';process.env.SUPABASE_SERVICE_ROLE_KEY='private-secret';
  const {openDb,convertDDL,rewriteSql}=require('../db-compat');
  assert.match(rewriteSql('SELECT MAX(x-y,0) FROM foo WHERE id=?'),/SELECT GREATEST\(x-y,0\).*id=\$1/);
  assert.equal(rewriteSql('UPDATE boxes SET reserved_quantity=MAX(reserved_quantity-?,0) WHERE id=?'),'UPDATE boxes SET reserved_quantity=GREATEST(reserved_quantity-$1,0) WHERE id=$2');
  assert.match(convertDDL('id INTEGER PRIMARY KEY AUTOINCREMENT, cost REAL NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP'),/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY.*DOUBLE PRECISION.*CURRENT_TIMESTAMP::text/);
  const db=openDb('/ignore/local.db');
  await db.exec('CREATE TABLE IF NOT EXISTS orders (id INTEGER PRIMARY KEY AUTOINCREMENT,total REAL);');
  const r=await db.prepare('INSERT INTO orders(total) VALUES(?)').run(12);
  assert.equal(r.lastInsertRowid,17);
  await db.prepare('INSERT OR IGNORE INTO studio_state VALUES(1,?)').run('x');
  await db.withTransaction(async()=>{await db.prepare('UPDATE boxes SET reserved_quantity=reserved_quantity+? WHERE id=?').run(1,4)});
  assert(calls.some(c=>/ON CONFLICT DO NOTHING/i.test(c.sql)));
  assert(calls.some(c=>/\$2/.test(c.sql)));
  assert(calls.some(c=>c.sql==='BEGIN'));
  assert(calls.some(c=>/pg_advisory_xact_lock/i.test(c.sql)));
  assert(calls.some(c=>c.sql==='COMMIT'));
  const st=require('../supabase-storage');
  const p=await st.upload('x.png',Buffer.from('abc'),{contentType:'image/png'});
  const q=await st.upload('p.png',Buffer.from('def'),{isPrivate:true,contentType:'image/png'});
  assert.match(p,/public\/nice-public\/uploads\/x.png/);
  assert.equal(q,'/private-media/p.png');
  await st.validateBucketVisibility();
  const d=await st.downloadPrivate('p.png');assert.equal(d.buffer.toString(),'private bytes');
  assert.equal(roleClient.secret,'private-secret');
  assert.equal(supabaseCalls.find(c=>c.bucket==='nice-private').file,'private-media/p.png');
  console.log('PASSED: PostgreSQL prepared SQL, DDL rewrite, transactions and Supabase public/private Storage mocks');
}
main().catch(e=>{console.error(e);process.exitCode=1});
